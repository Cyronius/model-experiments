"""Versioned semantic-risk quarantine, reviewed training expansion and audit.

No population-wide meaning certification: unreviewed operator changes are
quarantined conservatively, and 1800 authored expansions have only36 seed frames.
"""
from collections import Counter
import gzip
import hashlib
import io
import json
from pathlib import Path
import re
import sys
from tagger import ROOT,SteTokenizer
from rollouts import records,sha256
from prepare import input_paths
from ste_tokenizer import model_tokens
from safe_editor import validate
from protected_regions import regions
from reviewed_rewrites import canonical_words

OUT=ROOT/'data/out';PARENT=OUT/'id-joint-v3';DEST=OUT/'id-quality-v4b'
AUDIT=OUT/'data-quality-v4';VOCAB=OUT/'fixes-v1/vocabulary'
OPERATORS={'not','never','without','unless','if','whether','must','should','may','might','can','could','shall','will','would','before','after','otherwise','only'}


def prose_words(text):
    chars=list(text)
    for a,b in regions(text):chars[a:b]=' '*(b-a)
    return canonical_words(re.findall(r'[a-z]+', ''.join(chars).lower()))

def signature(text):
    return Counter('if' if w=='whether' else w for w in prose_words(text) if w in OPERATORS)

def reasons(row,manual):
    found=[];decision=manual.get(row['id'])
    if decision and decision['decision'] in ('exclude','review'):found.append('manual_'+decision['decision'])
    if row['kind']!='local_rule' and signature(row['src'])!=signature(row['ste']) and not (decision and decision['decision']=='approve'):
        found.append('operator_change_pending_review')
    if re.search(r'\b(a|an|the)\s+\1\b',row['ste'],re.I):
        words=prose_words(row['ste'])
        if any(a==b and a in ('a','an','the') for a,b in zip(words,words[1:])):found.append('target_duplicate_article')
    return found


def seeds():
    data=json.loads((ROOT/'model_tagger/benchmarks/reviewed-software-seeds-v1.json').read_text())
    swaps={'purpose':(' to ',' in order to '),'before':(' before ',' prior to '),'after':(' after ',' subsequent to '),
           'conditional':('If ','In the event that '),'because':(' because ',' due to the fact that '),'now':(' at this time.',' at this point in time.')}
    index=0
    for family,(old,new) in swaps.items():
        for target in data[family]:
            index+=1
            assert old in target
            yield index,family,target.replace(old,new,1),target


def instantiate(text,prefix):
    # Fixed literal substitutions only; no prose/meaning is generated by a model.
    return re.sub(r'`([^`]+)`',lambda m:'`'+prefix+'_'+m.group(1)+'`',text)


def authored_rows(tok):
    for index,family,source,target in seeds():
        for variant in range(50):
            prefix=f'train_quality4_{index:02}_{variant:02}'
            src,ste=instantiate(source,prefix),instantiate(target,prefix)
            if validate(src,ste):raise ValueError('seed fails reviewed guard: '+str(index))
            encoded=tok.encode_pair(dict(src=src,ste=ste,mode='PROC'),.7)
            key=hashlib.sha256((src+'\0'+ste).encode()).hexdigest()
            yield dict(encoded,schema='ste-id-pairs-v1',id='authored-v4-'+key,origin_id='authored-seed-'+str(index),
                       group='authored-quality4-seed-'+str(index),split='train',kind='reviewed',noise='reviewed_phrase_'+family,
                       meaning_review='assistant_reviewed_seed_owner_pending',src=src,ste=ste,mode='PROC',
                       provenance={'type':'literal-only expansion','seed':index,'family':family,'variant':variant,'independent_manual_pairs':False},
                       surface_bucket=encoded['bucket'])


def quarantine_groups(manual):
    groups={}
    for path,_ in input_paths(PARENT):
        for row in records(path):
            why=reasons(row,manual)
            if why:groups.setdefault(row['group'],set()).update(why)
    return groups


def build():
    if DEST.exists() and any(DEST.iterdir()):raise ValueError('use a fresh data destination')
    DEST.mkdir(parents=True);(DEST/'shards').mkdir()
    tok=SteTokenizer(VOCAB);manual={r['id']:r for r in json.loads((AUDIT/'manual-review.json').read_text())['reviews']}
    groups=quarantine_groups(manual)
    counts=Counter();buckets=Counter();removed=Counter();written=[];streams={};scanned=0;added=0
    curated=list(authored_rows(tok))
    authored_keys={tuple(t.text.casefold() for t in model_tokens(text)) for row in curated for text in (row['src'],row['ste'])}
    def close(split):
        text,raw=streams.pop(split);text.close();raw.close()
    def write(row):
        split=row['split']
        if counts[split]%25000==0:
            if split in streams:close(split)
            path=DEST/'shards'/f'{split}-{counts[split]//25000:05}.jsonl.gz';written.append(path)
            raw=path.open('wb');streams[split]=(io.TextIOWrapper(gzip.GzipFile(filename='',fileobj=raw,mode='wb',mtime=0,compresslevel=1),encoding='utf-8'),raw)
        streams[split][0].write(json.dumps(row,ensure_ascii=False,separators=(',',':'))+'\n');counts[split]+=1;buckets[str(row['bucket'])]+=1
    with (DEST/'rejected.jsonl').open('w') as rejected:
        for path,_ in input_paths(PARENT):
            for row in records(path):
                scanned+=1
                for text in (row['src'],row['ste']):
                    if 'train_quality4_' in text.lower() and tuple(t.text.casefold() for t in model_tokens(text)) in authored_keys:raise ValueError('authored pair collides with existing corpus')
                why=sorted(groups.get(row['group'],set()))
                if why:
                    removed.update(why);rejected.write(json.dumps(dict(id=row['id'],split=row['split'],kind=row['kind'],reasons=why))+'\n')
                else:write(row)
                if scanned%100000==0:print('quality revision scanned',scanned,flush=True)
        for row in curated:write(row);added+=1
    for split in list(streams):close(split)
    summary=dict(schema='ste-reviewed-id-revision-v4b',scanned=scanned,pairs=sum(counts.values()),splits=dict(counts),buckets=dict(buckets),
                 parent_summary_sha256=sha256(PARENT/'summary.json'),vocab_sha256=sha256(VOCAB/'vocab.json'),
                 added_authored_pairs=added,independently_reviewed_seed_frames=36,exclusion_rule_matches=dict(removed),quarantined_groups={g:sorted(v) for g,v in groups.items()},
                 manual_review_sha256=sha256(AUDIT/'manual-review.json'),revision_code_sha256=sha256(Path(__file__)),
                 review_phrase_sha256=sha256(Path(__file__).parent/'reviewed_rewrites.py'),
                 shards=[dict(path=p.relative_to(DEST).as_posix(),sha256=sha256(p)) for p in written],
                 limits=['Unreviewed operator changes are quarantined pending review, not declared wrong.','1800 training pairs are literal expansions of36 assistant-reviewed seeds, not1800 independent meaning judgments.','Whole implicated groups quarantined; retained payloads/splits/groups unchanged; authored additions train-only.'])
    (DEST/'summary.json').write_text(json.dumps(summary,indent=2)+'\n');return summary


def validate_revision():
    summary=json.loads((DEST/'summary.json').read_text());tok=SteTokenizer(VOCAB)
    if sha256(PARENT/'summary.json')!=summary['parent_summary_sha256'] or sha256(Path(__file__))!=summary['revision_code_sha256']:raise ValueError('revision changed')
    manual={r['id']:r for r in json.loads((AUDIT/'manual-review.json').read_text())['reviews']}
    groups=quarantine_groups(manual)
    if {g:sorted(v) for g,v in groups.items()}!=summary['quarantined_groups']:raise ValueError('quarantine groups changed')
    expected={};counts=Counter()
    for path,_ in input_paths(PARENT):
        for row in records(path):
            if row['group'] not in groups:expected[row['id']]=sha_payload(row)
    for row in authored_rows(tok):expected[row['id']]=sha_payload(row)
    for path,_ in input_paths(DEST):
        for row in records(path):
            if expected.pop(row['id'],None)!=sha_payload(row):raise ValueError('retained/added payload changed')
            counts[row['split']]+=1
    if expected or dict(counts)!=summary['splits']:raise ValueError('revision accounting mismatch')
    result=dict(passed=True,retained_and_authored_payloads_exact=True,splits=dict(counts),summary_sha256=sha256(DEST/'summary.json'))
    (DEST/'revision-validation.json').write_text(json.dumps(result,indent=2)+'\n');return result


def sha_payload(row):return hashlib.sha256(json.dumps(row,sort_keys=True).encode()).hexdigest()

if __name__=='__main__':
    print(json.dumps(build() if sys.argv[1]=='build' else validate_revision(),indent=2))
